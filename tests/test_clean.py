import contextlib
import io
from pathlib import Path
import tempfile
from types import SimpleNamespace
import unittest
from unittest.mock import patch

from balboa.clean import clean, plan
from balboa.cli import parser


class CleanTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.root = Path(self.directory.name)
        for name in ("build", "cache", "balboa/__pycache__"):
            (self.root / name).mkdir(parents=True)
        self.bytecode = self.root / "balboa/__pycache__/cli.pyc"
        self.bytecode.write_bytes(b"generated bytecode")
        self.site = self.root / "site.json"
        self.site.write_text("private site input")
        (self.root / "cache/official.iso").write_bytes(b"official media")
        self.disk = self.root / "build/system.qcow2"
        self.disk.write_bytes(b"existing VM")

    def arguments(self, **values):
        return SimpleNamespace(**{"build": False, "cache": False, "path": [], "apply": False, **values})

    def operate(self, **values):
        with contextlib.redirect_stdout(io.StringIO()) as output:
            clean(self.arguments(**values), self.root)
        return output.getvalue()

    def test_default_preview_and_apply_preserve_site_media_and_vm(self):
        self.assertIn("No files were removed", self.operate())
        self.assertTrue(self.bytecode.exists())
        self.operate(apply=True)
        self.assertFalse(self.bytecode.exists())
        for path in (self.site, self.disk, self.root / "cache/official.iso"):
            self.assertTrue(path.exists())

    def test_selected_child_and_complete_outputs_require_explicit_flags(self):
        for path in (self.root, self.site, self.root / "build/../site.json",
                     self.root / "build", self.root / "cache"):
            with self.subTest(path=path), self.assertRaises(ValueError):
                plan(self.arguments(path=[path]), self.root)
        self.operate(path=[self.disk], apply=True)
        self.assertFalse(self.disk.exists())
        self.assertTrue(self.site.exists())
        self.operate(build=True, cache=True, apply=True)
        self.assertFalse((self.root / "build").exists())
        self.assertFalse((self.root / "cache").exists())
        self.assertTrue(self.site.exists())

    def test_nested_selections_are_removed_only_once(self):
        selected = plan(self.arguments(build=True, path=[self.disk, self.disk]), self.root)
        self.assertEqual(selected.count(self.root / "build"), 1)
        self.assertNotIn(self.disk, selected)

    def test_target_and_parent_links_are_rejected_without_removal(self):
        link = self.root / "build/link"
        link.symlink_to(self.root / "cache", target_is_directory=True)
        for path in (link, link / "official.iso"):
            with self.subTest(path=path), self.assertRaises(ValueError):
                self.operate(path=[path], apply=True)
        self.assertTrue(self.bytecode.exists())
        self.assertTrue((self.root / "cache/official.iso").exists())

    def test_nested_link_does_not_remove_its_destination(self):
        (self.root / "build/site-link").symlink_to(self.site)
        (self.root / "build/cache-link").symlink_to(self.root / "cache", target_is_directory=True)
        self.operate(build=True, apply=True)
        self.assertEqual(self.site.read_text(), "private site input")
        self.assertTrue((self.root / "cache/official.iso").exists())

    def test_open_vm_disk_blocks_all_removals(self):
        with self.disk.open("rb"), self.assertRaisesRegex(ValueError, "No files were removed"):
            self.operate(build=True, apply=True)
        self.assertTrue(self.bytecode.exists())
        self.assertTrue(self.disk.exists())

    def test_mount_blocks_all_removals(self):
        with patch.object(Path, "is_mount", lambda path: path.name == "build"):
            with self.assertRaisesRegex(ValueError, "Unmount"):
                self.operate(build=True, apply=True)
        self.assertTrue(self.bytecode.exists())
        self.assertTrue(self.disk.exists())

    def test_cli_defaults_to_preview_and_no_build_or_cache_selection(self):
        args = parser().parse_args(["clean"])
        self.assertFalse(args.apply)
        self.assertFalse(args.build)
        self.assertFalse(args.cache)
        self.assertEqual(args.path, [])


if __name__ == "__main__":
    unittest.main()
